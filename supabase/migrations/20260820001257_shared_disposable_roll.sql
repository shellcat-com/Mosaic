create table public.shared_moments (
  id uuid primary key,
  challenge_id uuid not null references public.challenges(id) on delete cascade,
  creator_id uuid not null references auth.users(id) on delete cascade,
  editorial_category text,
  note text,
  media_path text,
  attribution text not null default 'anonymous',
  reveal_consent boolean not null default true,
  export_consent boolean not null default false,
  media_version integer not null default 1,
  consent_version integer not null default 1,
  lifecycle text not null default 'upload_pending',
  reported_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shared_moments_category check (editorial_category is null or editorial_category in ('encouragement','giving','community','teaching','support','connection')),
  constraint shared_moments_note_length check (note is null or char_length(note) <= 280),
  constraint shared_moments_attribution check (attribution in ('anonymous','permitted')),
  constraint shared_moments_lifecycle check (lifecycle in ('local_draft','upload_pending','sealed_pending_review','approved','rejected','deleted','reported','consent_revoked')),
  constraint shared_moments_media_versions check (media_version > 0 and consent_version > 0),
  constraint shared_moments_remote_not_local check (lifecycle <> 'local_draft')
);

create index shared_moments_challenge_state_idx on public.shared_moments(challenge_id, lifecycle, created_at);
create index shared_moments_creator_idx on public.shared_moments(creator_id, challenge_id, created_at desc);
create unique index shared_moments_media_path_unique on public.shared_moments(media_path) where media_path is not null;

create table public.shared_moment_reports (
