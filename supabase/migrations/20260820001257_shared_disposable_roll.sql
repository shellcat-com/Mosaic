create function private.guard_shared_moment_update()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.creator_id <> new.creator_id or old.challenge_id <> new.challenge_id or old.created_at <> new.created_at then
    raise exception 'immutable shared moment ownership';
  end if;
  if not private.is_challenge_organizer(old.challenge_id) then
    if new.lifecycle not in ('upload_pending','sealed_pending_review','approved','deleted','consent_revoked') then
      raise exception 'invalid owner lifecycle transition';
    end if;
    if new.lifecycle = 'approved' and old.lifecycle <> 'approved' then
      raise exception 'only organizers approve shared moments';
    end if;
    if old.reported_at is distinct from new.reported_at then raise exception 'reported state is server managed'; end if;
    new.consent_version := old.consent_version + case when old.reveal_consent is distinct from new.reveal_consent or old.export_consent is distinct from new.export_consent then 1 else 0 end;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create trigger guard_shared_moment_update before update on public.shared_moments
for each row execute function private.guard_shared_moment_update();

create function private.flag_shared_moment_report()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update public.shared_moments set reported_at = now(), lifecycle = 'reported' where id = new.moment_id;
  return new;
end;
$$;
create trigger flag_shared_moment_report after insert on public.shared_moment_reports
for each row execute function private.flag_shared_moment_report();

create function private.refresh_shared_roll_count()
returns trigger language plpgsql security definer set search_path = '' as $$
declare target uuid := coalesce(new.challenge_id, old.challenge_id);
begin
  insert into public.shared_roll_counts(challenge_id, sealed_count, approved_count, updated_at)
  select target,
    count(*) filter (where lifecycle in ('upload_pending','sealed_pending_review','approved')),
    count(*) filter (where lifecycle = 'approved' and reveal_consent and deleted_at is null and reported_at is null), now()
  from public.shared_moments where challenge_id = target
  on conflict (challenge_id) do update set sealed_count = excluded.sealed_count,
    approved_count = excluded.approved_count, updated_at = excluded.updated_at;
  return coalesce(new, old);
end;
$$;
create trigger refresh_shared_roll_count after insert or update or delete on public.shared_moments
for each row execute function private.refresh_shared_roll_count();

create function private.prune_engagement_events()
returns integer language plpgsql security definer set search_path = '' as $$
declare removed integer;
begin
  delete from public.engagement_events where occurred_at < now() - interval '30 days';
  get diagnostics removed = row_count;
  return removed;
end;
$$;

